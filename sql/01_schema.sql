BEGIN;
CREATE SCHEMA estate;
CREATE TABLE estate.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL CHECK (btrim(full_name) <> ''),
    login text NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE estate.roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE estate.user_roles (
    user_id bigint NOT NULL REFERENCES estate.users(id),
    role_id bigint NOT NULL REFERENCES estate.roles(id),
    PRIMARY KEY(user_id,role_id)
);

CREATE TABLE estate.clients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL CHECK (btrim(full_name) <> ''),
    phone text NOT NULL CHECK (btrim(phone) <> ''),
    email text,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint NOT NULL REFERENCES estate.users(id),
    deleted_at timestamptz,
    deleted_by bigint REFERENCES estate.users(id),
    CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);

CREATE TABLE estate.property_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE estate.properties (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id bigint NOT NULL REFERENCES estate.property_types(id),
    address text NOT NULL CHECK (btrim(address) <> ''),
    area numeric(10,2) NOT NULL CHECK(area>0),
    description text NOT NULL DEFAULT '',
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint NOT NULL REFERENCES estate.users(id),
    deleted_at timestamptz,
    deleted_by bigint REFERENCES estate.users(id),
    CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);

CREATE TABLE estate.property_owners (
    property_id bigint NOT NULL REFERENCES estate.properties(id),
    client_id bigint NOT NULL REFERENCES estate.clients(id),
    PRIMARY KEY(property_id,client_id)
);

CREATE TABLE estate.property_photos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id bigint NOT NULL REFERENCES estate.properties(id),
    url text NOT NULL,
    sort_order integer NOT NULL DEFAULT 0 CHECK(sort_order>=0)
);

CREATE TABLE estate.amenities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE estate.property_amenities (
    property_id bigint NOT NULL REFERENCES estate.properties(id),
    amenity_id bigint NOT NULL REFERENCES estate.amenities(id),
    PRIMARY KEY(property_id,amenity_id)
);

CREATE TABLE estate.listings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id bigint NOT NULL REFERENCES estate.properties(id),
    agent_id bigint NOT NULL REFERENCES estate.users(id),
    kind text NOT NULL CHECK(kind IN ('sale','rent')),
    price numeric(14,2) NOT NULL CHECK(price>0),
    status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','closed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint NOT NULL REFERENCES estate.users(id),
    deleted_at timestamptz,
    deleted_by bigint REFERENCES estate.users(id),
    CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);

CREATE TABLE estate.listing_price_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES estate.listings(id),
    old_price numeric(14,2),
    new_price numeric(14,2) NOT NULL CHECK(new_price>0),
    changed_at timestamptz NOT NULL DEFAULT now(),
    changed_by bigint NOT NULL REFERENCES estate.users(id)
);

CREATE TABLE estate.viewing_appointments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES estate.listings(id),
    client_id bigint NOT NULL REFERENCES estate.clients(id),
    agent_id bigint NOT NULL REFERENCES estate.users(id),
    starts_at timestamptz NOT NULL,
    status text NOT NULL DEFAULT 'planned' CHECK(status IN ('planned','done','cancelled')),
    UNIQUE(agent_id,
    starts_at)
);

CREATE TABLE estate.offers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES estate.listings(id),
    client_id bigint NOT NULL REFERENCES estate.clients(id),
    amount numeric(14,2) NOT NULL CHECK(amount>0),
    status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','accepted','rejected')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE estate.contracts (
    id uuid PRIMARY KEY,
    listing_id bigint NOT NULL UNIQUE REFERENCES estate.listings(id),
    amount numeric(14,2) NOT NULL CHECK(amount>0),
    signed_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint NOT NULL REFERENCES estate.users(id)
);

CREATE TABLE estate.contract_participants (
    contract_id uuid NOT NULL REFERENCES estate.contracts(id),
    client_id bigint NOT NULL REFERENCES estate.clients(id),
    role text NOT NULL CHECK(role IN ('owner','customer')),
    PRIMARY KEY(contract_id,client_id)
);

CREATE TABLE estate.payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id uuid NOT NULL REFERENCES estate.contracts(id),
    amount numeric(14,2) NOT NULL CHECK(amount>0),
    paid_at timestamptz NOT NULL DEFAULT now(),
    recorded_by bigint NOT NULL REFERENCES estate.users(id)
);

CREATE TABLE estate.audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name text NOT NULL,
    record_id text NOT NULL,
    operation text NOT NULL CHECK(operation IN ('INSERT','UPDATE')),
    old_data jsonb,
    new_data jsonb NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT now(),
    changed_by bigint NOT NULL REFERENCES estate.users(id)
);


CREATE INDEX ix_listings_price ON estate.listings USING btree(price) WHERE deleted_at IS NULL AND status='active';
CREATE INDEX ix_properties_search ON estate.properties USING gin(to_tsvector('simple',address || ' ' || description)) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX ux_active_listing ON estate.listings(property_id,kind) WHERE deleted_at IS NULL AND status='active';
CREATE INDEX ix_payments_contract ON estate.payments(contract_id);
CREATE INDEX ix_owners_client ON estate.property_owners(client_id);
CREATE INDEX ix_participants_client ON estate.contract_participants(client_id);
COMMIT;
